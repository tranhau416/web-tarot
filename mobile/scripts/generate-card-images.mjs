// Writes src/lib/cardImages.ts: a static require() for every card image in
// frontend/public/cards, keyed by the file name the backend puts in image_url.
// React Native can only bundle images named in a literal require(), hence the generated map.
import { readdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const cardsDir = path.resolve(here, "../../frontend/public/cards")
const files = readdirSync(cardsDir).filter((f) => f.endsWith(".webp")).sort()

const lines = files.map((f) => `  ${JSON.stringify(f)}: require("../../../frontend/public/cards/${f}"),`)
const out = `// Generated by scripts/generate-card-images.mjs — do not edit by hand.
import type { ImageSourcePropType } from "react-native"

export const CARD_IMAGES: Record<string, ImageSourcePropType> = {
${lines.join("\n")}
}
`
writeFileSync(path.resolve(here, "../src/lib/cardImages.ts"), out)
console.log(`cardImages.ts: ${files.length} images`)
